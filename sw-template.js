/*
 * sw-template.js — заготовка service worker'а мира.
 *
 * В сборку не импортируется и Vite его не разбирает: плагин `serviceWorker()`
 * из vite.config.js читает этот файл, подставляет три метки-заполнителя (путь
 * мира, версию сборки и список файлов оболочки - они помечены двойными
 * подчёркиваниями в объявлениях ниже) и кладёт готовый `sw.js` рядом с
 * бандлом. Отсюда и стиль без модулей: файл исполняется в worker'е как есть.
 *
 * Метки поэтому не поминаем в комментариях дословно: подстановка глобальная и
 * заменила бы их и здесь.
 *
 * Зачем он вообще, если nginx и так отдаёт ассеты с годовым `immutable`.
 * Затем, что html мира отдаётся с `no-cache`, и каждый приход начинается с
 * обращения к серверу: пока оно не вернулось, не начинается вообще ничего.
 * Плюс браузерный кэш на телефоне вычищается тем охотнее, чем меньше в
 * телефоне места, — а пять мегабайт моделей это первый кандидат на вылет.
 * Service worker убирает и то, и другое: второй приход в мир начинается с
 * нулевой сетью, а мир, однажды загруженный целиком, открывается и без неё.
 *
 * Кэша два, и это не усложнение ради усложнения.
 *
 *   Оболочка (версия сборки в имени) — html, boot и бандлы. Живёт ровно одну
 *   версию: вышла новая сборка — старая выбрасывается целиком, иначе мир
 *   остался бы на старом коде навсегда.
 *
 *   Отделка (имя без версии) — модели, текстуры, wasm-декодер. Адрес каждого
 *   такого файла несёт штамп содержимого (`?v=` из `asset.js`), поэтому
 *   изменившийся файл приезжает по новому адресу сам, а выбрасывать вместе с
 *   кодом ещё и пять мегабайт моделей, которые не менялись, незачем.
 *
 * У отделки нет и не может быть списка: что игрок загрузил, то и лежит.
 * Поэтому единственный сторож — потолок по числу записей: устаревшие адреса
 * после нескольких выкладок копятся, и когда их становится заметно больше,
 * чем файлов у мира, кэш отделки сбрасывается целиком и набирается заново.
 */

const SCOPE = '__SCOPE__';
const VERSION = '__VERSION__';
const SHELL_CACHE = `fte-shell${SCOPE.replace(/\//g, '-')}${VERSION}`;
const ASSET_CACHE = `fte-assets${SCOPE.replace(/\//g, '-')}`;
const SHELL = __SHELL__;

// Потолок записей в кэше отделки. У миров сейчас шесть десятков файлов; втрое
// больше — это уже мусор от нескольких выкладок, а не мир.
const ASSET_LIMIT = 200;

// Сколько ждём сеть на заходе в мир, прежде чем отдать кэш. Полторы секунды —
// это заметно больше обычного ответа сервера (сотня миллисекунд) и заметно
// меньше того, что человек считает зависшей страницей.
const NAV_TIMEOUT = 1500;

self.addEventListener('install', (e) => {
  e.waitUntil(
    caches
      .open(SHELL_CACHE)
      .then((c) => c.addAll(SHELL))
      // Ждать закрытия старых вкладок незачем: оболочка версионирована именем
      // кэша, и новый worker не может подсунуть старой вкладке чужие файлы.
      .then(() => self.skipWaiting())
      // A partial shell must never replace the last complete offline release.
      .catch(async (error) => { await caches.delete(SHELL_CACHE); throw error; })
  );
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(
        names
          .filter((n) => n.startsWith(`fte-shell${SCOPE.replace(/\//g, '-')}`) && n !== SHELL_CACHE)
          .map((n) => caches.delete(n))
      );
      const assets = await caches.open(ASSET_CACHE);
      if ((await assets.keys()).length > ASSET_LIMIT) await caches.delete(ASSET_CACHE);
      await self.clients.claim();
    })()
  );
});

/** Ответ, который можно класть в кэш: свой, целый, не кусок. */
const storable = (r) => r && r.ok && r.type === 'basic' && r.status === 200;

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  if (url.origin !== location.origin || !url.pathname.startsWith(SCOPE)) return;
  // Сам worker всегда берётся из сети: иначе мир не сможет обновиться никогда.
  if (url.pathname === `${SCOPE}sw.js`) return;

  // Заход в мир: СНАЧАЛА СЕТЬ, кэш — подстраховка.
  //
  // Раньше было наоборот: страница отдавалась из кэша сразу, а свежая тянулась
  // в фоне и доставалась игроку со следующего прихода. Рассуждение было такое:
  // имена бандлов версионированы, значит «свежее» и «то же самое» — одно и то
  // же. Оно неверно ровно в тот момент, когда сборка меняется: вернувшийся
  // получал вчерашнюю страницу со вчерашними именами бандлов — то есть
  // вчерашний мир целиком, — и новая выкладка доходила до него только со
  // второго захода. Проверить свежую сборку было нельзя: браузер показывал
  // предыдущую и выглядело это как «не выложено».
  //
  // Хуже того, это могло вообще не собраться. Старая страница ссылается на
  // старые имена бандлов, а выкладка их уже заменила — по этим адресам на
  // сервере 404. Кэш оболочки к тому времени вычищен активацией нового
  // worker'а, так что взять их неоткуда.
  //
  // Плата за исправление — одна маленькая страница по сети (4-5 КБ сжатой) на
  // каждый заход. Оффлайн при этом остаётся: нет сети или она молчит дольше
  // TIMEOUT — отдаём кэш, как и раньше.
  if (req.mode === 'navigate') {
    e.respondWith(
      (async () => {
        // Хвост адреса тут не различает ничего: `?debug`, `?reset`, `?quality`
        // читает код мира, а страница по всем ним отдаётся одна и та же.
        // Поэтому ищем без него и кладём всегда по чистому адресу - иначе в
        // кэше копились бы копии одного html под каждым хвостом.
        const cached = () =>
          caches.match(SCOPE, { cacheName: SHELL_CACHE, ignoreVary: true });
        const live = fetch(req)
          .then(async (r) => {
            if (storable(r)) e.waitUntil((await caches.open(SHELL_CACHE)).put(SCOPE, r.clone()).catch(() => {}));
            return r;
          })
          .catch(() => null);
        // Сеть ждём, но не бесконечно: на мёртвом соединении мир должен
        // открыться из кэша, а не висеть на белом экране.
        const raced = await Promise.race([
          live,
          new Promise((resolve) => setTimeout(() => resolve(null), NAV_TIMEOUT)),
        ]);
        return raced || (await cached()) || (await live) || Response.error();
      })()
    );
    return;
  }

  e.respondWith(
    (async () => {
      // Хвост адреса у отделки, наоборот, значим до последнего знака: штамп
      // содержимого (`?v=`) и есть ключ кэша. Ищем как есть.
      const shell = await caches.match(req, { cacheName: SHELL_CACHE });
      if (shell) return shell;
      const assets = await caches.open(ASSET_CACHE);
      const hit = await assets.match(req);
      if (hit) return hit;
      const r = await fetch(req);
      if (storable(r)) e.waitUntil(assets.put(req, r.clone()).catch(() => {}));
      return r;
    })()
  );
});
